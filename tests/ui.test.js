globalThis.runUITests = async () => {
  let count=0;
  const assert=(ok,label)=>{if(!ok)throw new Error(label);count++;};
  const settle=async()=>{for(let i=0;i<25;i++)await Promise.resolve();};
  const submit=async id=>{elements[id].onsubmit({preventDefault(){}});await settle();};
  assert(elements['host-view'].hidden,'Organizer panel hidden on startup');
  assert(!elements['player-view'].hidden&&!elements['join-panel'].hidden,'Room entry is first screen');
  assert(elements['game-toolbar'].hidden,'No host tab offered to guests');
  elements['organizer-login'].onclick();
  assert(elements['login-dialog'].open,'Organizer button opens login');
  assert(!elements['demo-host'].hidden&&elements['login-submit'].hidden,'Offline demo clearly separate from login');
  await elements['demo-host'].onclick();
  assert(!elements['host-view'].hidden,'Explicit demo opens organizer panel');
  elements['party-name'].value='Fiesta de prueba';elements['create-style'].value='line_full';
  await submit('create-form');
  const rooms=JSON.parse(localStorage.getItem('bingo-demo-rooms'));
  const code=Object.keys(rooms)[0];
  assert(Boolean(code),'Host creates a room');
  await elements['fullscreen'].onclick();
  assert(!elements['presentation'].hidden,'Fullscreen opens dedicated projection');
  assert(elements['presentation-code'].textContent===code,'Projection includes room code');
  await elements['presentation-last'].onclick();
  assert(elements['presentation-count'].textContent==='0 / 75','Roulette candidates are not counted as drawn');
  assert(!elements['presentation-last'].disabled,'Roulette can be stopped to choose a result');
  await elements['presentation-last'].onclick();
  assert(JSON.parse(localStorage.getItem('bingo-demo-rooms'))[code].drawn.length===1,'Repeated click does not draw an extra number');
  assert(flushAnimation()>=22,'Roulette cycles candidates slowly before revealing');
  assert(elements['presentation-count'].textContent==='0 / 75','Projection waits to mark the chosen number');
  assert(Number(elements['presentation-number'].textContent)===JSON.parse(localStorage.getItem('bingo-demo-rooms'))[code].drawn[0],'Revealed number is the actual stored result');
  assert(!elements['reveal'].hidden,'Chosen number appears over fullscreen projection');
  elements['reveal-close'].onclick();
  assert(elements['presentation-count'].textContent==='1 / 75','Projection marks result after confirmation');
  for(let i=0;i<11;i++){await elements['presentation-last'].onclick();flushAnimation();elements['reveal-close'].onclick();}
  assert(elements['presentation-history'].children.length===12,'Projection shows complete history beyond last ten');
  await elements['presentation-room'].onclick();
  assert(elements['presentation'].hidden,'Room code exits fallback fullscreen');
  // Start a new round to allow the player to join after testing the display.
  elements['restart'].onclick();elements['round-style'].value='line_full';await submit('round-form');
  await elements['presentation-last'].onclick();
  // Ya fuera de proyección, el resultado debe esperar una confirmación manual.
  flushAnimation();
  assert(!elements['reveal'].hidden,'Chosen number remains open outside projection');
  elements['reveal-close'].onclick();
  assert(elements['reveal'].hidden,'Chosen number closes only from its button');
  elements['restart'].onclick();elements['round-style'].value='line_full';await submit('round-form');
  elements['player-tab'].onclick();elements['room-code'].value='ZZZZZZ';await submit('code-form');
  assert(elements['entry-message'].textContent.includes('No encontramos'),'Invalid code displays error');
  elements['room-code'].value=code;await submit('code-form');
  assert(!elements['join-form'].hidden&&elements['code-form'].hidden,'Existing room asks for name');
  elements['player-name'].value='Fran';await submit('join-form');
  assert(!elements['card-panel'].hidden&&elements['join-panel'].hidden,'Successful join displays card');
  const before=localStorage.getItem('bingo-demo-rooms');
  elements['leave-room'].onclick();elements['room-code'].value=code;await submit('code-form');
  assert(!elements['card-panel'].hidden,'Room code recovers existing card without another name');
  assert(localStorage.getItem('bingo-demo-rooms')===before,'Recovering card does not create another player');
  await elements['logout'].onclick();
  assert(elements['host-view'].hidden&&elements['host-tab'].hidden,'Logout hides organizer controls');
  assert(localStorage.getItem('bingo-demo-rooms')===before,'Logout preserves rooms and player cards');
  return `${count} UI flow assertions passed (simulated DOM)`;
};
