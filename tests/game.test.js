(() => {
  let count = 0;
  const assert = (value, label) => { if (!value) throw new Error(label); count++; };
  const rejects = (fn, label) => { let rejected=false;try{fn();}catch{rejected=true;}assert(rejected,label); };
  const G = BingoGame;
  const card = Array.from({length:25},(_,i) => i===12 ? 0 : (i%5)*15+Math.floor(i/5)+1);
  const numbers = indices => indices.map(i=>card[i]).filter(Boolean);
  const row = numbers([0,1,2,3,4]);
  const column = numbers([1,6,11,16,21]);
  const diagonal = numbers([0,6,12,18,24]);
  const reverse = numbers([4,8,12,16,20]);
  const corners = numbers([0,4,20,24]);
  assert(G.matches(card,row,'line'),'Horizontal line');
  assert(G.matches(card,column,'line'),'Vertical line');
  assert(G.matches(card,diagonal,'line'),'Diagonal and free center');
  assert(G.matches(card,reverse,'line'),'Reverse diagonal');
  assert(!G.matches(card,row.slice(1),'line'),'Incomplete line rejected');
  assert(G.matches(card,corners,'corners'),'Four corners');
  assert(!G.matches(card,corners.slice(1),'corners'),'Incomplete corners rejected');
  assert(G.matches(card,[...diagonal,...reverse],'x'),'Both diagonals form X');
  assert(!G.matches(card,diagonal,'x'),'Single diagonal is not X');
  assert(!G.matches(card,row,'full'),'Line is not full card');
  assert(G.matches(card,card.filter(Boolean),'full'),'Full card without center');
  assert(!G.matches(card,card.filter(n=>n&&n!==card[0]),'full'),'Missing number prevents full bingo');
  assert(!G.matches(card,card,'unknown'),'Unknown pattern rejected');
  assert(!G.matches([],[],'full'),'Malformed card rejected');
  for(const stages of Object.values(G.presets)) assert(G.validStages(stages),'Preset supported');
  assert(!G.validStages(['full','line']),'Invalid stage order');

  const room=()=>({code:'ABC123',title:'Fiesta',host:'host',drawn:[],players:[],winner:null,stages:['line','full'],stage:0,round:1,awards:[]});
  const r=room();
  const mutate=(action, extra={})=>G.mutate(r,action,{token:'host',round:r.round,stage:r.stage,...extra},()=>[...card],()=>0);
  mutate('join',{token:'player',name:'Fran'});
  const original=JSON.stringify(r.players);
  r.drawn=[...row];
  rejects(()=>mutate('claim',{token:'stranger'}),'Unknown player cannot claim');
  rejects(()=>mutate('restart',{token:'player',stages:['full']}),'Player cannot restart');
  rejects(()=>mutate('configure',{stages:['full']}),'Cannot change style after first draw');
  rejects(()=>mutate('advance'),'Cannot skip a prize before a winner');
  rejects(()=>mutate('draw',{round:0}),'Reject draw from stale round');
  mutate('claim',{token:'player'});
  assert(r.winner==='player'&&r.awards.length===1,'Binguito records winner once');
  rejects(()=>mutate('claim',{token:'player'}),'Duplicate claim rejected');
  rejects(()=>mutate('draw'),'Drawing pauses at intermediate prize');
  mutate('advance');
  assert(r.stage===1&&r.winner===null&&JSON.stringify(r.drawn)===JSON.stringify(row),'Advance keeps drawn numbers');
  assert(r.awards[0].pattern==='line','Intermediate winner retained');
  rejects(()=>mutate('claim',{token:'player',stage:0}),'Old-stage claim rejected');
  rejects(()=>mutate('claim',{token:'player'}),'Incomplete full card claim rejected');
  r.drawn=card.filter(Boolean);
  mutate('claim',{token:'player'});
  assert(r.winner==='player'&&r.awards.length===2,'Same player may win both prizes');
  rejects(()=>mutate('advance'),'Cannot advance after final prize');
  mutate('restart',{stages:['corners','full']});
  assert(r.round===2&&r.drawn.length===0&&r.awards.length===0&&r.winner===null&&r.stage===0,'Restart clears round state');
  assert(JSON.stringify(r.players)===original&&r.code==='ABC123'&&r.host==='host','Restart preserves room, players, cards and host');
  rejects(()=>mutate('restart',{round:1,stages:['full']}),'Duplicate delayed restart rejected');
  mutate('join',{token:'player',name:'Other name'});
  assert(JSON.stringify(r.players)===original,'Reconnect keeps original card and name');
  mutate('join',{token:'player2',name:'Cami'});
  assert(r.players.length===2,'New players may join between rounds');
  mutate('configure',{stages:['full']});
  assert(r.stages.length===1&&r.round===2,'Configure does not increment round');
  for(let i=0;i<75;i++)mutate('draw');
  assert(new Set(r.drawn).size===75&&Math.min(...r.drawn)===1&&Math.max(...r.drawn)===75,'75 unique draws in range');
  rejects(()=>mutate('draw'),'76th draw rejected');
  rejects(()=>mutate('join',{token:'late',name:'Late'}),'Late player must wait for restart');
  mutate('join',{token:'player',name:'Fran'});
  assert(r.players.length===2,'Existing player can reconnect after start');
  const legacy={code:'OLD123',title:'Legacy',host:'host',drawn:[],players:[],winner:null};
  G.normalize(legacy);
  assert(legacy.round===1&&legacy.stages[0]==='full'&&legacy.stage===0,'Old demo rooms migrate without losing state');
  globalThis.testResult = `${count} game assertions passed`;
})();
